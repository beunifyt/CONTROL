let _currentLang = (typeof localStorage !== 'undefined' && localStorage.getItem('beunifyt_lang')) || 'es';
if(!T[_currentLang]) _currentLang = 'es';

export function getLang(){ return _currentLang; }

export function setLang(code){
  if(!T[code]) code = 'es';
  _currentLang = code;
  try{ localStorage.setItem('beunifyt_lang', code); } catch(_){}
  if(typeof document !== 'undefined'){
    document.documentElement.lang = code;
    document.dispatchEvent(new CustomEvent('lang-changed', { detail: { code } }));
  }
}

export function tr(key, fallback, ...args){
  let val = T[_currentLang]?.[key] ?? T.es?.[key] ?? fallback ?? key;
  if(args.length){
    args.forEach((a, i) => { val = String(val).replace(new RegExp('\\{' + i + '\\}', 'g'), a); });
  }
  return val;
}

/**
 * Traduce una clave para un idioma SPECÍFICO (no el actual).
 * Útil para imprimir pase en idioma del conductor.
 */
export function trIn(lang, key, fallback, ...args){
  let val = T[lang]?.[key] ?? T.es?.[key] ?? fallback ?? key;
  if(args.length){
    args.forEach((a, i) => { val = String(val).replace(new RegExp('\\{' + i + '\\}', 'g'), a); });
  }
  return val;
}

